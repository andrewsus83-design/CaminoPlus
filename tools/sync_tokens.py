#!/usr/bin/env python3
"""Keep the design tokens in step across the repository.

design/tokens.css and design/tokens.json are the single source of truth. This script:

  1. writes web/assets/tokens.css from design/tokens.css (the website's copy),
  2. checks that design/tokens.json and mobile/src/theme/tokens.json are the same file,
  3. checks that tokens.css and tokens.json agree on the values they both carry
     (colours, type sizes and line heights, spacing, radius, layout, icon sizes).

Usage:
  python3 tools/sync_tokens.py            write web/assets/tokens.css, then run the checks
  python3 tools/sync_tokens.py --check    write nothing, exit 1 if anything is out of step (CI)

Never edit web/assets/tokens.css by hand and never edit design/tokens.* from here: change
design/tokens.css and design/tokens.json, then run this script.

The web copy differs from design/tokens.css in one way: the Google Fonts @import is removed,
because the website serves its fonts itself (web/assets/fonts, @font-face in web/assets/site.css),
so visitors do not send their IP address to Google. Pass --keep-font-import to keep it.
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DESIGN_CSS = ROOT / "design" / "tokens.css"
DESIGN_JSON = ROOT / "design" / "tokens.json"
MOBILE_JSON = ROOT / "mobile" / "src" / "theme" / "tokens.json"
WEB_CSS = ROOT / "web" / "assets" / "tokens.css"

FONT_IMPORT = re.compile(r'^@import url\("https://fonts\.googleapis\.com[^"]*"\);[ \t]*\n', re.M)
WEB_HEADER = (
    "/* GENERATED by tools/sync_tokens.py from design/tokens.css. Do not edit here: change the design\n"
    "   file, then run `python3 tools/sync_tokens.py`. The only difference is that the Google Fonts\n"
    "   @import is gone: this site serves Fraunces, Inter, JetBrains Mono and Caveat itself\n"
    "   (assets/fonts, @font-face in site.css). */\n\n"
)


def web_copy(keep_font_import: bool = False) -> str:
    css = DESIGN_CSS.read_text(encoding="utf-8")
    if not keep_font_import:
        css, n = FONT_IMPORT.subn("", css)
        if n != 1:
            raise SystemExit("sync_tokens: expected exactly one Google Fonts @import in design/tokens.css, found %d" % n)
    return WEB_HEADER + css


def css_vars(css: str) -> dict[str, str]:
    """--cp-* custom properties declared in :root, last declaration wins (like the cascade)."""
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"(--cp-[a-z0-9-]+)\s*:\s*([^;]+);", css)}


def kebab(name: str) -> str:
    """goldInk -> gold-ink, blue900 -> blue-900, tabbarHeight -> tabbar-height"""
    s = re.sub(r"(?<=[a-z])(?=[A-Z0-9])", "-", name)
    return s.lower()


def px(value: str) -> float | None:
    m = re.fullmatch(r"(-?[\d.]+)(?:px)?", value)
    return float(m.group(1)) if m else None


def compare_css_json(css: dict[str, str], data: dict) -> list[str]:
    """Differences between tokens.css and tokens.json for the groups both of them define."""
    problems = []

    def check(var: str, expected, kind: str):
        have = css.get(var)
        if have is None:
            problems.append(f"{var} is in tokens.json but not in tokens.css")
        elif kind == "px":
            if px(have) != float(expected):
                problems.append(f"{var}: css {have}, json {expected}")
        elif have.lower() != str(expected).lower():
            problems.append(f"{var}: css {have}, json {expected}")

    for k, v in data["color"].items():
        # success colours are semantic roles in the css (--cp-success), plain colours in the json
        var = f"--cp-{kebab(k)}" if k.startswith("success") else f"--cp-color-{kebab(k)}"
        check(var, v, "hex")
    for name, t in data["text"].items():
        check(f"--cp-text-{name}-size", t["size"], "px")
        check(f"--cp-text-{name}-lh", t["lineHeight"], "px")
    for k, v in data["space"].items():
        check(f"--cp-space-{k}", v, "px")
    for k, v in data["radius"].items():
        check(f"--cp-radius-{k}", v, "px")
    for k, v in data["layout"].items():
        check(f"--cp-{kebab(k)}", v, "px")
    for k, v in data["icon"].items():
        check(f"--cp-icon-{kebab(k)}", v, "px")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when anything is out of step")
    ap.add_argument("--keep-font-import", action="store_true", help="keep the Google Fonts @import in the web copy")
    args = ap.parse_args()

    problems = []
    want = web_copy(args.keep_font_import)
    have = WEB_CSS.read_text(encoding="utf-8") if WEB_CSS.exists() else None
    if have != want:
        if args.check:
            problems.append(f"{WEB_CSS.relative_to(ROOT)} is not a copy of design/tokens.css: run `python3 tools/sync_tokens.py`")
        else:
            WEB_CSS.write_text(want, encoding="utf-8")
            print(f"wrote {WEB_CSS.relative_to(ROOT)}")
    else:
        print(f"{WEB_CSS.relative_to(ROOT)} is up to date")

    if DESIGN_JSON.read_bytes() != MOBILE_JSON.read_bytes():
        problems.append(f"{MOBILE_JSON.relative_to(ROOT)} differs from design/tokens.json: copy the design file over it")
    else:
        print("design/tokens.json == mobile/src/theme/tokens.json")

    for line in compare_css_json(css_vars(DESIGN_CSS.read_text(encoding="utf-8")), json.loads(DESIGN_JSON.read_text(encoding="utf-8"))):
        problems.append("design tokens disagree: " + line)

    for p in problems:
        print("ERROR:", p, file=sys.stderr)
    if problems:
        return 1
    print("tokens in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
