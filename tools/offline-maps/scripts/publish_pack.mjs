// Upload a built pack and register it in public.offline_packs.
//
//   node scripts/publish_pack.mjs dist/camino-frances-01-3km-z15.json \
//        [--target supabase|r2] [--version 20261104] [--dry-run]
//
// --target supabase (default for now): private Storage bucket "offline-packs",
//   url 'supabase://offline-packs/<key>'.
// --target r2 (later, Cloudflare): bucket $R2_BUCKET, url 'r2://<bucket>/<key>'.
// The offline-pack-url edge function signs either kind, so moving to R2 is:
// re-publish with --target r2 (or copy the files) and the url column follows.
//
// Reads the manifest that build_stage.sh wrote next to the .pmtiles file.
//
// Key:  <route_slug>/stage-<NN>/tiles-v<version>.pmtiles   (immutable; a new build = a new key)
// Row:  offline_packs(route_id, stage_id, kind 'tiles', format 'pmtiles', version,
//                     url, size_bytes, sha256, is_current true)
//          and every older 'tiles' row for that stage gets is_current = false.
//
// Env:
//   SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY  upload (target supabase) and registering the row
//   R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_BUCKET  only for --target r2
//
// Always writes <manifest>.offline_packs.sql with the same upsert, so the row can
// also be applied by hand (supabase db query, SQL editor) if the API keys are not set.
import { AwsClient } from 'aws4fetch';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';

const argv = process.argv.slice(2);
const manifestPath = argv.find((a) => a.endsWith('.json'));
const dryRun = argv.includes('--dry-run');
const vIdx = argv.indexOf('--version');
const tIdx = argv.indexOf('--target');
const target = tIdx > 0 ? argv[tIdx + 1] : 'supabase';
if (!['supabase', 'r2'].includes(target)) { console.error('--target must be supabase or r2'); process.exit(1); }
if (!manifestPath) { console.error('usage: publish_pack.mjs <pack manifest .json> [--version N] [--dry-run]'); process.exit(1); }

const m = JSON.parse(await readFile(manifestPath, 'utf8'));
const file = join(dirname(manifestPath), m.file);
const body = await readFile(file);

// Integrity: recompute, never trust the manifest blindly.
const sha256 = createHash('sha256').update(body).digest('hex');
if (sha256 !== m.sha256 || body.length !== m.size_bytes) throw new Error('pack file does not match its manifest');

// Version = OSM data date as YYYYMMDD (fits the integer column, sorts, one per monthly build).
const version = vIdx > 0 ? Number(argv[vIdx + 1]) : Number((m.osm_timestamp || new Date().toISOString()).slice(0, 10).replaceAll('-', ''));
const bucket = target === 'r2' ? (process.env.R2_BUCKET || 'caminoplus-packs') : 'offline-packs';
const key = `${m.route_slug}/stage-${String(m.stage_number).padStart(2, '0')}/tiles-v${version}.pmtiles`;
const url = `${target === 'r2' ? 'r2' : 'supabase'}://${bucket}/${key}`;

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const sql = `-- offline_packs row for ${m.file} (generated by publish_pack.mjs)
begin;
update public.offline_packs set is_current = false
 where route_id = ${q(m.route_id)} and stage_id = ${q(m.stage_id)} and kind = 'tiles' and version <> ${version};
insert into public.offline_packs (route_id, stage_id, kind, format, version, url, size_bytes, sha256, is_current)
values (${q(m.route_id)}, ${q(m.stage_id)}, 'tiles', 'pmtiles', ${version}, ${q(url)}, ${m.size_bytes}, ${q(sha256)}, true)
on conflict do nothing;
update public.offline_packs set url = ${q(url)}, size_bytes = ${m.size_bytes}, sha256 = ${q(sha256)}, is_current = true, deleted_at = null
 where route_id = ${q(m.route_id)} and stage_id = ${q(m.stage_id)} and kind = 'tiles' and version = ${version};
commit;
`;
const sqlPath = manifestPath.replace(/\.json$/, '.offline_packs.sql');
await writeFile(sqlPath, sql);
console.log(`pack ${m.file}: ${body.length} bytes, sha256 ${sha256}`);
console.log(`target ${url}`);
console.log(`wrote ${sqlPath}`);
if (dryRun) process.exit(0);

// 1. Upload. Single request is fine: stage packs are a few MB.
const { SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY } = process.env;
const common = {
  'Content-Type': 'application/vnd.pmtiles',
  // Keys are versioned, so the object never changes: cache it forever.
  'Cache-Control': 'public, max-age=31536000, immutable',
};
if (target === 'supabase') {
  if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY) throw new Error('missing env SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY');
  const up = await fetch(`${SUPABASE_URL}/storage/v1/object/${bucket}/${key}`, {
    method: 'POST',
    body,
    headers: {
      ...common,
      'x-upsert': 'true',
      apikey: SUPABASE_SERVICE_ROLE_KEY,
      Authorization: `Bearer ${SUPABASE_SERVICE_ROLE_KEY}`,
    },
  });
  if (!up.ok) throw new Error(`Storage upload ${up.status}: ${await up.text()}`);
  console.log(`uploaded to Supabase Storage (${up.status})`);
} else {
  for (const k of ['R2_ACCOUNT_ID', 'R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY']) {
    if (!process.env[k]) throw new Error(`missing env ${k}`);
  }
  const r2 = new AwsClient({
    accessKeyId: process.env.R2_ACCESS_KEY_ID,
    secretAccessKey: process.env.R2_SECRET_ACCESS_KEY,
    service: 's3',
    region: 'auto',
  });
  const put = await r2.fetch(`https://${process.env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com/${bucket}/${key}`, {
    method: 'PUT',
    body,
    headers: { ...common, 'x-amz-meta-sha256': sha256, 'x-amz-meta-osm-timestamp': m.osm_timestamp || '' },
  });
  if (!put.ok) throw new Error(`R2 PUT ${put.status}: ${await put.text()}`);
  console.log(`uploaded to R2 (${put.status})`);
}

// 2. Register in Supabase through PostgREST with the service role (bypasses RLS).
if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY) {
  console.log('SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY not set: apply the SQL file by hand');
  process.exit(0);
}
const rest = (path, init) => fetch(`${SUPABASE_URL}/rest/v1/${path}`, {
  ...init,
  headers: {
    apikey: SUPABASE_SERVICE_ROLE_KEY,
    Authorization: `Bearer ${SUPABASE_SERVICE_ROLE_KEY}`,
    'Content-Type': 'application/json',
    Prefer: 'return=minimal',
    ...(init.headers || {}),
  },
});
const scope = `route_id=eq.${m.route_id}&stage_id=eq.${m.stage_id}&kind=eq.tiles`;
let r = await rest(`offline_packs?${scope}&version=neq.${version}`, { method: 'PATCH', body: JSON.stringify({ is_current: false }) });
if (!r.ok) throw new Error(`retire old packs: ${r.status} ${await r.text()}`);
const row = { route_id: m.route_id, stage_id: m.stage_id, kind: 'tiles', format: 'pmtiles', version, url, size_bytes: m.size_bytes, sha256, is_current: true, deleted_at: null };
r = await rest(`offline_packs?${scope}&version=eq.${version}`, { method: 'PATCH', body: JSON.stringify(row), headers: { Prefer: 'return=representation' } });
if (!r.ok) throw new Error(`update pack: ${r.status} ${await r.text()}`);
if ((await r.json()).length === 0) {
  r = await rest('offline_packs', { method: 'POST', body: JSON.stringify(row) });
  if (!r.ok) throw new Error(`insert pack: ${r.status} ${await r.text()}`);
}
console.log(`registered offline_packs version ${version} (is_current)`);
