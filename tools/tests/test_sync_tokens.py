"""Tests for tools/sync_tokens.py. Run from the repository root:  python3 -m unittest discover -s tools/tests -v"""
import copy
import json
import pathlib
import subprocess
import sys
import unittest

TOOLS = pathlib.Path(__file__).resolve().parent.parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))

import sync_tokens  # noqa: E402


class WebCopy(unittest.TestCase):
    def test_only_the_font_import_and_a_header_differ(self):
        design = (ROOT / "design" / "tokens.css").read_text(encoding="utf-8")
        web = sync_tokens.web_copy()
        self.assertTrue(web.startswith("/* GENERATED by tools/sync_tokens.py"))
        self.assertNotIn("fonts.googleapis.com", web)
        body = web[len(sync_tokens.WEB_HEADER):]
        self.assertEqual(body, sync_tokens.FONT_IMPORT.sub("", design))
        self.assertIn("--cp-text-body-size:    19px", body)       # the drift this script exists to prevent
        self.assertIn("--cp-touch-min:          56px", body)

    def test_keep_font_import_option(self):
        self.assertIn("fonts.googleapis.com", sync_tokens.web_copy(keep_font_import=True))

    def test_committed_copy_is_in_sync(self):
        self.assertEqual((ROOT / "web" / "assets" / "tokens.css").read_text(encoding="utf-8"), sync_tokens.web_copy())

    def test_the_check_mode_passes_on_the_repository(self):
        r = subprocess.run([sys.executable, str(TOOLS / "sync_tokens.py"), "--check"], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("tokens in sync", r.stdout)


class CssJsonAgreement(unittest.TestCase):
    def setUp(self):
        self.css = sync_tokens.css_vars((ROOT / "design" / "tokens.css").read_text(encoding="utf-8"))
        self.data = json.loads((ROOT / "design" / "tokens.json").read_text(encoding="utf-8"))

    def test_design_files_agree(self):
        self.assertEqual(sync_tokens.compare_css_json(self.css, self.data), [])

    def test_a_changed_value_is_reported(self):
        css = dict(self.css, **{"--cp-text-body-size": "17px"})
        problems = sync_tokens.compare_css_json(css, self.data)
        self.assertEqual(problems, ["--cp-text-body-size: css 17px, json 19"])
        data = copy.deepcopy(self.data)
        data["color"]["gold"] = "#000000"
        self.assertIn("--cp-color-gold: css #D9A21B, json #000000", sync_tokens.compare_css_json(self.css, data))

    def test_a_missing_token_is_reported(self):
        css = {k: v for k, v in self.css.items() if k != "--cp-touch-min"}
        self.assertEqual(sync_tokens.compare_css_json(css, self.data), ["--cp-touch-min is in tokens.json but not in tokens.css"])

    def test_names(self):
        self.assertEqual([sync_tokens.kebab(n) for n in ("goldInk", "blue900", "tabbarHeight", "gold")], ["gold-ink", "blue-900", "tabbar-height", "gold"])

    def test_the_two_json_files_are_one_file(self):
        self.assertEqual((ROOT / "design" / "tokens.json").read_bytes(), (ROOT / "mobile" / "src" / "theme" / "tokens.json").read_bytes())


if __name__ == "__main__":
    unittest.main()
